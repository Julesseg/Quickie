import Foundation

/// One swatch's sRGB fill as pure numbers (0…1), so the palette's legibility is Core
/// data a `swift test` can *measure* rather than App vocabulary that can only be
/// eyeballed. The App turns one of these into a `Color` at its badge edge — the same
/// defer-to-the-edge split the kind-derived badge tints already use.
public struct ActionColorComponents: Equatable, Sendable {
    public let red: Double
    public let green: Double
    public let blue: Double

    public init(red: Double, green: Double, blue: Double) {
        self.red = red
        self.green = green
        self.blue = blue
    }

    /// Builds a swatch from 8-bit channels — how the palette below is written, since
    /// the generator emits them that way.
    init(_ r: Int, _ g: Int, _ b: Int) {
        self.init(red: Double(r) / 255, green: Double(g) / 255, blue: Double(b) / 255)
    }

    /// WCAG relative luminance — the input to the contrast ratio below.
    var relativeLuminance: Double {
        func linear(_ channel: Double) -> Double {
            channel <= 0.03928 ? channel / 12.92 : pow((channel + 0.055) / 1.055, 2.4)
        }
        return 0.2126 * linear(red) + 0.7152 * linear(green) + 0.0722 * linear(blue)
    }

    /// The WCAG contrast ratio between this fill and the **white** badge symbol drawn
    /// on it — the arithmetic behind "tuned for legibility", pinned by `ActionColorTests`
    /// to the same 4.4–5.6 band `docs/brand/check-brand-assets.py` holds the provider
    /// badges to, so a user-chosen swatch is exactly as readable as a derived one.
    var contrastRatioAgainstWhite: Double {
        1.05 / (relativeLuminance + 0.05)
    }
}

/// The curated **Action color** palette (CONTEXT.md → Action color; issue #243): the
/// closed set of named tints a user may give an Action, the glyph's sibling
/// customization. Ten tokens plus **Default** — which is the *absence* of a token, not
/// an eleventh case, so "no choice" and "the provider-kind-derived tint" are the same
/// state and an untouched action renders exactly as before.
///
/// A token, never a raw hex string: the stored value is one of these names, so the
/// actual fills stay centrally tuned here and a palette revision reaches every stored
/// action at once.
///
/// ## How these values were derived
///
/// These are **not** hand-picked hex values. They were generated by the same method and
/// the same tool as the provider-badge ring (`docs/brand/badge-palette-methodology.md`,
/// `prototype_badge_palette.py`; issue #178, PR #189), because a user-chosen badge and a
/// kind-derived one are the *same badge* and must read as one family:
///
/// - **OKLCH lightness 0.55**, the badge ring's lightness. Every badge carries a white
///   glyph, so every badge owes it the same legibility; fixing lightness pins
///   white-contrast into a tight band (these land 4.51–5.52:1, inside the ring's
///   4.4–5.6) and leaves **hue** as the only channel that varies — the channel that
///   actually carries the identity.
/// - **Chroma at each hue's sRGB gamut ceiling, capped at 0.24** — the ring's vivid
///   setting, so a chosen colour is as saturated as its hue allows without leaving the
///   family. (This is why teal reads quieter than purple: teal's ceiling is 0.095.)
/// - **Flat literals, not a light/dark pair.** At this lightness one opaque colour sits
///   correctly on both appearances, which is exactly why the badge ring is flat too —
///   matching it is what keeps a user swatch from being the one badge that shifts when
///   the appearance does.
///
/// Where this palette *departs* from the ring: the ring deliberately leaves the accent
/// (~290°) and gold (~84°) arcs empty so an assigned badge never reads as a broken
/// accent or spends ADR 0033's gold. This palette keeps Amber, Indigo, and Purple
/// anyway — a *user* picking purple is a deliberate choice, not an accident the way a
/// mis-assigned kind hue would be, and a colour picker missing the obvious names would
/// read as broken. A considered exception to rule 4, not an oversight; the brand check
/// guards the `badge*` tokens and is untouched by it.
///
/// Raw values are a **persisted format** (the store column, the widget snapshot key),
/// so renaming a case must keep its raw value.
public enum ActionColor: String, CaseIterable, Equatable, Sendable {
    case red
    case orange
    /// The legible stand-in for yellow: a true yellow can never hold a white symbol
    /// (its contrast against white is ~1.4:1), so the palette ships the ochre that can.
    case amber
    case green
    case teal
    case blue
    case indigo
    case purple
    case pink
    /// The neutral — for the actions whose identity isn't a hue (a settings link, a
    /// utility) but which still want to read apart from their provider's default.
    /// Achromatic at the same lightness, so it sits in the family rather than beside it.
    case graphite

    /// Everything one token *is*: its picker name and its fill. Deliberately **one**
    /// switch rather than two parallel ones, so a new token cannot be half-added.
    private var entry: (label: String, fill: ActionColorComponents) {
        switch self {
        case .red:      return ("Red",      ActionColorComponents(214, 0, 3))
        case .orange:   return ("Orange",   ActionColorComponents(175, 84, 0))
        case .amber:    return ("Amber",    ActionColorComponents(141, 109, 0))
        case .green:    return ("Green",    ActionColorComponents(0, 138, 35))
        case .teal:     return ("Teal",     ActionColorComponents(0, 131, 126))
        case .blue:     return ("Blue",     ActionColorComponents(0, 116, 200))
        case .indigo:   return ("Indigo",   ActionColorComponents(82, 83, 249))
        case .purple:   return ("Purple",   ActionColorComponents(148, 52, 222))
        case .pink:     return ("Pink",     ActionColorComponents(205, 0, 108))
        case .graphite: return ("Graphite", ActionColorComponents(113, 113, 113))
        }
    }

    /// The human name shown beside the swatch in the editor's colour picker.
    public var label: String { entry.label }

    /// This token's fill — the single place a name becomes numbers.
    public var components: ActionColorComponents { entry.fill }

    /// Resolves a **stored** token string to a palette entry, or `nil` for Default.
    /// The single tolerant read point every persisted surface goes through: an absent,
    /// blank, unknown (a future build's token), or hex-shaped value all resolve to
    /// Default — the kind-derived tint — so a synced record this build can't render
    /// degrades to today's behaviour rather than to a blank or a crash. Trimmed and
    /// case-folded so a hand-edited or migrated value still lands.
    public init?(token: String?) {
        guard let token else { return nil }
        let normalized = token.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        guard !normalized.isEmpty, let match = ActionColor(rawValue: normalized) else { return nil }
        self = match
    }
}
